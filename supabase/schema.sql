drop policy if exists profiles_select_own_or_admin on public.profiles;
create policy profiles_select_own_or_admin on public.profiles
  for select to authenticated
  using (id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists profiles_update_own on public.profiles;
create policy profiles_update_own on public.profiles
  for update to authenticated
  using (id = (select auth.uid()))
  with check (id = (select auth.uid()));

drop policy if exists admin_users_select_self_or_admin on public.admin_users;
create policy admin_users_select_self_or_admin on public.admin_users
  for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists complaints_select_own_or_admin on public.complaints;
create policy complaints_select_own_or_admin on public.complaints
  for select to authenticated
  using (user_id = (select auth.uid()) or (select public.is_admin()));

drop policy if exists complaints_insert_own on public.complaints;
create policy complaints_insert_own on public.complaints
  for insert to authenticated
  with check (user_id = (select auth.uid()));

drop policy if exists complaints_update_admin on public.complaints;
create policy complaints_update_admin on public.complaints
  for update to authenticated
  using ((select public.is_admin()))
  with check ((select public.is_admin()));

drop policy if exists complaints_history_select_own_or_admin on public.complaint_status_history;
create policy complaints_history_select_own_or_admin on public.complaint_status_history
  for select to authenticated
  using (
    (select public.is_admin())
    or exists (
      select 1 from public.complaints c
      where c.id = complaint_id and c.user_id = (select auth.uid())
    )
  );

