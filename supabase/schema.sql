create extension if not exists pgcrypto;

create table if not exists public.profiles (
  id uuid primary key references auth.users(id) on delete cascade,
  username text unique,
  full_name text not null default '',
  phone text,
  email text,
  avatar_url text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  constraint profiles_username_format check (
    username is null or username ~ '^[a-zA-Z0-9_.-]{3,40}$'
  )
);

create table if not exists public.admin_users (
  user_id uuid primary key references public.profiles(id) on delete cascade,
  created_at timestamptz not null default now()
);

do $$
begin
  create type public.complaint_status as enum
    ('pending', 'in_progress', 'resolved', 'rejected');
exception
  when duplicate_object then null;
end
$$;

create table if not exists public.complaints (
  id bigint generated by default as identity primary key,
  tracking_code text not null unique default ('CVL-' || upper(substr(encode(gen_random_bytes(5), 'hex'), 1, 8))),
  user_id uuid not null references public.profiles(id) on delete cascade,
  category text not null,
  title text not null,
  description text not null default '',
  status public.complaint_status not null default 'pending',
  severity smallint,
  image_path text,
  image_content_type text,
  image_sha256 text,
  exif_latitude numeric(9,6) not null,
  exif_longitude numeric(9,6) not null,
  exif_captured_at timestamptz,
  exif_metadata jsonb not null default '{}'::jsonb,
  ward text,
  assigned_department text,
  admin_note text,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  resolved_at timestamptz,
  constraint complaints_category_not_blank check (length(trim(category)) >= 2),
  constraint complaints_title_not_blank check (length(trim(title)) >= 3),
  constraint complaints_latitude_range check (exif_latitude between -90 and 90),
  constraint complaints_longitude_range check (exif_longitude between -180 and 180),
  constraint complaints_severity_range check (severity is null or severity between 1 and 5)
);

create table if not exists public.complaint_status_history (
  id bigint generated by default as identity primary key,
  complaint_id bigint not null references public.complaints(id) on delete cascade,
  changed_by uuid references public.profiles(id) on delete set null,
  from_status public.complaint_status,
  to_status public.complaint_status not null,
  note text,
  created_at timestamptz not null default now()
);

create index if not exists complaints_user_id_created_at_idx
  on public.complaints(user_id, created_at desc);
create index if not exists complaints_status_created_at_idx
  on public.complaints(status, created_at desc);
create index if not exists complaints_category_idx
  on public.complaints(category);
create index if not exists complaints_coordinates_idx
  on public.complaints(exif_latitude, exif_longitude);
create index if not exists complaint_status_history_complaint_idx
  on public.complaint_status_history(complaint_id, created_at desc);

create or replace function public.is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.admin_users
    where user_id = (select auth.uid())
  );
$$;

create or replace function public.set_updated_at()
returns trigger
language plpgsql
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

create or replace function public.handle_new_auth_user()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  insert into public.profiles (id, username, full_name, phone, email, avatar_url)
  values (
    new.id,
    nullif(new.raw_user_meta_data ->> 'username', ''),
    coalesce(new.raw_user_meta_data ->> 'full_name', ''),
    coalesce(new.raw_user_meta_data ->> 'phone', new.raw_user_meta_data ->> 'mobile_number', new.phone),
    lower(new.email),
    new.raw_user_meta_data ->> 'avatar_url'
  )
  on conflict (id) do update set
    email = excluded.email,
    phone = coalesce(excluded.phone, profiles.phone),
    full_name = case when excluded.full_name <> '' then excluded.full_name else profiles.full_name end,
    updated_at = now();
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute procedure public.handle_new_auth_user();

drop trigger if exists profiles_set_updated_at on public.profiles;
create trigger profiles_set_updated_at
  before update on public.profiles
  for each row execute procedure public.set_updated_at();

drop trigger if exists complaints_set_updated_at on public.complaints;
create trigger complaints_set_updated_at
  before update on public.complaints
  for each row execute procedure public.set_updated_at();

create or replace function public.write_complaint_status_history()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if tg_op = 'INSERT' then
    insert into public.complaint_status_history (complaint_id, changed_by, to_status)
    values (new.id, new.user_id, new.status);
  elsif old.status is distinct from new.status then
    insert into public.complaint_status_history (complaint_id, changed_by, from_status, to_status, note)
    values (new.id, (select auth.uid()), old.status, new.status, new.admin_note);
  end if;
  return new;
end;
$$;

drop trigger if exists complaints_status_history on public.complaints;
create trigger complaints_status_history
  after insert or update of status on public.complaints
  for each row execute procedure public.write_complaint_status_history();

