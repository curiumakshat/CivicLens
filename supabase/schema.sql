create policy complaint_images_delete_own_or_admin on storage.objects
  for delete to authenticated
  using (bucket_id = 'complaint-images' and (owner_id = (select auth.uid())::text or (select public.is_admin())));

create or replace view public.admin_complaint_analytics
with (security_invoker = true)
as
select
  category,
  status,
  count(*)::bigint as complaint_count,
  round(avg(extract(epoch from (coalesce(resolved_at, now()) - created_at)) / 86400)::numeric, 2) as avg_age_days
from public.complaints
group by category, status;

grant select on public.admin_complaint_analytics to authenticated;

